  const normalise = (value) => String(value == null ? '' : value)
    .replace(/[„”“]/g, '"').replace(/[’]/g, "'").replace(/\s+/g, ' ').trim();
  const NORMAL_EN = new Map(Object.entries(EN).map(([source, translated]) => [normalise(source), translated]));

  function storedLanguage() {
    try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ro'; }
    catch (e) { return 'ro'; }
  }
  let current = storedLanguage();

  // Păstrează emoji-ul/punctuația de la începutul butoanelor și traduce eticheta propriu-zisă.
  function translateRomanian(value) {
    const raw = String(value == null ? '' : value);
    if (!raw) return raw;
    if (Object.prototype.hasOwnProperty.call(EN, raw)) return EN[raw];
    const normal = normalise(raw);
    if (NORMAL_EN.has(normal)) return NORMAL_EN.get(normal);
    const prefix = raw.match(/^([^0-9A-Za-zĂÂÎȘȚăâîșț]*)([\s\S]*)$/);
    if (prefix && prefix[1]) {
      if (Object.prototype.hasOwnProperty.call(EN, prefix[2])) return prefix[1] + EN[prefix[2]];
      const suffix = normalise(prefix[2]);
      if (NORMAL_EN.has(suffix)) return prefix[1] + NORMAL_EN.get(suffix);
    }
    for (const [pattern, replacement] of DYNAMIC) {
      if (pattern.test(raw)) return raw.replace(pattern, replacement);
    }
    // Titlurile numerotate din fluxuri: „1 · Încarcă…” păstrează numărul și separatorul.
    const numbered = raw.match(/^(\d+\s*[·.]\s*)(.+)$/);
    if (numbered && Object.prototype.hasOwnProperty.call(EN, numbered[2])) return numbered[1] + EN[numbered[2]];
    // Sumele deja randate înainte de comutare primesc convenția engleză fără rerandarea
    // ecranului (important pentru formularele începute): 1.234,50 -> 1,234.50, 2,25% -> 2.25%.
    return raw.replace(/(^|[^\d,])((?:\d{1,3}(?:\.\d{3})+|\d+),\d+)(?!\.\d)\b/g, (_, lead, number) => {
      const decimals = (number.split(',')[1] || '').length;
      const value = Number(number.replace(/\./g, '').replace(',', '.'));
      return lead + (Number.isFinite(value) ? value.toLocaleString('en-GB', { minimumFractionDigits: decimals, maximumFractionDigits: decimals }) : number);
    });
  }

  function t(value) {
    return current === 'en' ? translateRomanian(value) : String(value == null ? '' : value);
  }

  function skipped(node) {
    const el = node.nodeType === ELEMENT_NODE ? node : node.parentElement;
    return !el || SKIP.has(el.tagName) || !!el.closest('[data-no-i18n]');
  }

  function applyText(node) {
    if (!node || skipped(node)) return;
    const previous = textApplied.get(node);
    if (!textSource.has(node) || (previous !== undefined && node.nodeValue !== previous)) textSource.set(node, node.nodeValue);
    const source = textSource.get(node);
    const lead = (source.match(/^\s*/) || [''])[0];
    const tail = (source.match(/\s*$/) || [''])[0];
    const core = source.slice(lead.length, source.length - tail.length);
    const next = lead + (current === 'en' ? translateRomanian(core) : core) + tail;
    textApplied.set(node, next);
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function applyAttrs(el) {
    if (!el || skipped(el)) return;
    let state = attrState.get(el);
    if (!state) { state = Object.create(null); attrState.set(el, state); }
    ATTRS.forEach((name) => {
      if (!el.hasAttribute(name)) return;
      const actual = el.getAttribute(name);
      const item = state[name];
      if (!item || actual !== item.applied) state[name] = { source: actual, applied: actual };
      const next = current === 'en' ? translateRomanian(state[name].source) : state[name].source;
      state[name].applied = next;
      if (actual !== next) el.setAttribute(name, next);
    });
  }

  // Unele explicații sunt împărțite de marcaje pur vizuale (<b>/<span>), deci niciun nod text
  // nu conține propoziția completă din catalog. Pentru paragrafe fără controale sau linkuri este
  // sigur să localizăm propoziția ca întreg; la revenirea pe RO restaurăm exact HTML-ul original.
  function applyWhole(el) {
    if (!el || skipped(el) || !el.matches || !el.matches('p, figcaption')) return;
    const state = wholeState.get(el);
    if (current === 'ro') {
      if (state && state.applied) { state.applied = false; el.innerHTML = state.sourceHtml; }
      return;
    }
    if (state && state.applied) return;
    if (el.querySelector('a,button,input,select,textarea')) return;
    const sourceText = state ? state.sourceText : normalise(el.textContent);
    if (!NORMAL_EN.has(sourceText)) return;
    const next = state || { sourceText, sourceHtml: el.innerHTML, applied: false };
    wholeState.set(el, next);
    next.applied = true;
    el.textContent = NORMAL_EN.get(sourceText);
  }

  function bindSwitches(root) {
    const switches = [];
    if (root && root.matches && root.matches('.language-switch')) switches.push(root);
    if (root && root.querySelectorAll) switches.push(...root.querySelectorAll('.language-switch'));
    switches.forEach((select) => {
      select.value = current;
      if (select.dataset.languageBound) return;
      select.dataset.languageBound = '1';
      select.addEventListener('change', () => setLanguage(select.value));
    });
  }

  function applyRoot(root) {
    if (!root) return;
    if (root.nodeType === TEXT_NODE) { applyText(root); return; }
    if (root.nodeType !== ELEMENT_NODE && root.nodeType !== DOCUMENT_NODE && root.nodeType !== DOCUMENT_FRAGMENT_NODE) return;
    if (root.nodeType === ELEMENT_NODE) { applyWhole(root); applyAttrs(root); }
    if (root.querySelectorAll) {
      root.querySelectorAll('p,figcaption').forEach(applyWhole);
      root.querySelectorAll('*').forEach(applyAttrs);
    }
    const walker = document.createTreeWalker(root, SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) applyText(node);
    bindSwitches(root);
  }

  function syncSwitches() {
    document.querySelectorAll('.language-switch').forEach((select) => { select.value = current; });
  }

  function setLanguage(language) {
    const next = language === 'en' ? 'en' : 'ro';
    const changed = next !== current;
    current = next;
    try { localStorage.setItem(STORAGE_KEY, current); } catch (e) { /* stocarea poate fi blocată */ }
    document.documentElement.lang = current;
    applyRoot(document);
    syncSwitches();
    if (changed) document.dispatchEvent(new CustomEvent('contab:language', { detail: { language: current, locale: locale() } }));
  }

  function locale() { return current === 'en' ? 'en-GB' : 'ro-RO'; }
  function language() { return current; }

  window.contabI18n = Object.freeze({ t, setLanguage, language, locale, translateRoot: applyRoot });

  function init() {
    document.documentElement.lang = current;
    applyRoot(document);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === 'characterData') applyText(mutation.target);
        else if (mutation.type === 'attributes') applyAttrs(mutation.target);
        else mutation.addedNodes.forEach(applyRoot);
      });
    });
    observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
